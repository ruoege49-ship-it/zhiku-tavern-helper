import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createComicController, comicBlocks} from '../src/comic.js';

const source = fs.readFileSync(new URL('../runtime.js', import.meta.url), 'utf8');
const start = source.indexOf('const __mod_model =');
const end = source.indexOf('// ───── store.js', start);
const M = vm.runInNewContext(source.slice(start, end) + '\n__mod_model', {structuredClone});
let data = M.emptyData();
const main = M.createFromString(data, {name:'Main', text:'artist:alpha', neg:'main_bad', forceGroup:true});
const comic = M.createFromString(data, {name:'Comic', text:'artist:beta', neg:'monochrome, greyscale, grayscale, screentone, text, comic_bad', forceGroup:true});
data.active = main;
Object.assign(data.options, {comicStyle:`group:${comic.id}`, comicColor:'mono', comicSize:'1024x1024', comicText:'none', comicPages:3, comicExtra:'Use wide shots.'});
data = M.normalizeData(JSON.parse(JSON.stringify(data)));
const body = '<image>@page\ncomic, 1boy\n@panel P1\nrainy street</image>';
const context = {chatId:'test', chat:[{mes:body}, {mes:'<content>A boy watches the rain.</content>'}], saveChat:async()=>{}};
const requests = [], adaptations = [];
const doc = {defaultView:{setTimeout,clearTimeout},head:{appendChild(){}},createElement:()=>({remove(){}}),querySelector:()=>null,querySelectorAll:()=>[],addEventListener(){},removeEventListener(){}};
const ctrl = createComicController({document:doc, getData:()=>data, getContext:()=>context, model:M, esc:String, notify(){}, generatePage:async r=>{requests.push(r);return {image:'image'};}, storeImage:async()=>({url:'saved.png'}), askLLM:async(system,user,options)=>{adaptations.push({system,user,options});return body;}});
await ctrl.generateOne(0, comicBlocks(body)[0]);
let req = requests.at(-1);
assert.match(req.positive,/artist:beta/);
assert(!req.positive.includes('artist:alpha'));
assert.match(req.positive,/monochrome, greyscale, screentone/);
for(const word of ['monochrome','greyscale','grayscale','screentone']) assert(!req.negative.includes(word), word);
assert.match(req.negative,/comic_bad/);
assert.equal(req.width,1024);assert.equal(req.height,1024);
assert.equal(data.active.id,main.id);
data.options.comicPages=8;data.options.comicPanels='1–2';
await ctrl.adapt(1);
assert.match(adaptations[0].user,/8 页黑白网点漫画，每页 1–2 格/);
assert.match(adaptations[0].user,/Use wide shots\./);assert.equal(adaptations[0].options.maxTokens,16000);
assert.equal(context.chat[1].mes,'<content>A boy watches the rain.</content>');
data.options.comicColor='color';
await ctrl.generateOne(0,comicBlocks(body)[0]);
assert(!requests.at(-1).positive.includes('monochrome'));
assert.match(requests.at(-1).negative,/monochrome/);
M.deleteGroup(data,comic.id);
await ctrl.generateOne(0,comicBlocks(body)[0]);
assert.match(requests.at(-1).positive,/artist:alpha/);
assert.match(requests.at(-1).negative,/main_bad/);
ctrl.stop();
console.log('PASS: persisted comic settings, independent style and deletion fallback, monochrome conflict filtering, dimensions and adaptation page/color/extra parameters.');
